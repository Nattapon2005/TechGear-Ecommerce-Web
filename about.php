<script>
// ===== Intersection Observer for scroll animations =====
const observerOptions = {
    threshold: 0.1,
    rootMargin: '0px 0px -50px 0px'
};

const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
        if (entry.isIntersecting) {
            entry.target.classList.add('animate-in');
            
            // Counter animation for stat numbers
            if (entry.target.classList.contains('stat-card')) {
                animateCounter(entry.target);
            }
        }
    });
}, observerOptions);

// Observe all animatable elements
document.querySelectorAll('.stat-card, .mission-content, .mission-visual, .timeline-item, .team-card, .why-card').forEach(el => {
    observer.observe(el);
});

// Counter animation
function animateCounter(card) {
    const numberEl = card.querySelector('.stat-number');
    const text = numberEl.textContent;
    // Simple reveal - just add animation class
    numberEl.style.opacity = '1';
}

// Parallax effect for hero
window.addEventListener('scroll', () => {
    const scrolled = window.scrollY;
    const hero = document.querySelector('.about-hero-content');
    if (hero && scrolled < 800) {
        hero.style.transform = `translateY(${scrolled * 0.3}px)`;
        hero.style.opacity = 1 - (scrolled / 800);
    }
});
</script>
